"""Generating the Python that runs a simulation.

The caller never supplies Python. A run is described by a parameter dict, a list
of steps and the *name* of a measurement; this renders the script that isicellpy
would have been asked to run, and every value crosses into it as JSON rather
than as source text. That keeps a run tool from becoming a way to execute
arbitrary code in the simulation process.

Measurements map to the vectorised getters SWIG puts on Simu.cells
(core/external/isicellpy/swig/BaseProject.i:225-442).
"""

from __future__ import annotations

import json
from dataclasses import dataclass

# name -> (expression evaluated on `simu`, what it returns)
CATCHERS: dict[str, tuple[str, str]] = {
    "countState": ("simu.cells.countState()", "cells in each state, per step"),
    "countType": ("simu.cells.countType()", "cells of each type, per step"),
    "population": ("{'n': len(simu.cells)}", "total live cells, per step"),
    "step": ("{'step': simu.getCurrentStep()}", "the step index only"),
}

# A named attribute is read through cells.get(), which is the documented way to
# pull one column out and is checked against cells.attrs at run time.
ATTRIBUTE_CATCHER = "attribute:"

TEMPLATE = '''"""Generated by mcp_isicell. Edit the model, not this file."""
import json
import sys

from isicell import Simu

PARAMS = json.loads({params!r})
STEPS = json.loads({steps!r})
SEED = json.loads({seed!r})


def catcher(simu):
    return {catcher_expr}


def main():
    simu = Simu(PARAMS) if SEED is None else Simu(PARAMS, SEED)
    out = {{}}
    for step in STEPS:
        target = int(step)
        current = simu.getCurrentStep()
        if target > current:
            simu.update(target - current)
        value = catcher(simu)
        if hasattr(value, "to_dict"):
            value = value.to_dict()
        out[str(target)] = value
    json.dump({{"ok": True, "data": out}}, sys.stdout)
    sys.stdout.write("\\n")


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:  # report the failure as data, not as a traceback
        json.dump({{"ok": False, "error": "%s: %s" % (type(exc).__name__, exc)}}, sys.stdout)
        sys.stdout.write("\\n")
        raise
'''


@dataclass(frozen=True)
class RunSpec:
    params: dict
    steps: list[int]
    catcher: str = "countState"
    seed: int | None = None


def catcher_expression(catcher: str) -> str:
    """The expression for a named measurement, or an attribute read."""
    if catcher in CATCHERS:
        return CATCHERS[catcher][0]
    if catcher.startswith(ATTRIBUTE_CATCHER):
        attribute = catcher[len(ATTRIBUTE_CATCHER) :].strip()
        if not attribute.isidentifier():
            raise ValueError(
                f"attribute name {attribute!r} is not an identifier; "
                "write it as 'attribute:<name>'"
            )
        # json.dumps keeps the name a literal, so nothing is interpolated as code.
        return f"{{'{attribute}': simu.cells.get({json.dumps(attribute)})}}"
    raise ValueError(
        f"unknown catcher {catcher!r}. Use one of {sorted(CATCHERS)}, "
        "or 'attribute:<name>' to read one recorded attribute."
    )


def describe_catchers() -> list[dict[str, str]]:
    out = [{"name": k, "returns": v[1]} for k, v in CATCHERS.items()]
    out.append(
        {
            "name": "attribute:<name>",
            "returns": "the named cell attribute for every live cell, per step",
        }
    )
    return out


def render(spec: RunSpec) -> str:
    """The full script for a run. Values are embedded as JSON, never as code."""
    if not spec.steps:
        raise ValueError("a run needs at least one step to measure at")
    steps = sorted({int(s) for s in spec.steps})
    if steps[0] < 0:
        raise ValueError("steps must not be negative")
    return TEMPLATE.format(
        params=json.dumps(spec.params),
        steps=json.dumps(steps),
        seed=json.dumps(spec.seed),
        catcher_expr=catcher_expression(spec.catcher),
    )
